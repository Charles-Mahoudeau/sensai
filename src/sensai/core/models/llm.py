"""Immutable models for chat messages and model responses."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import timedelta
from types import MappingProxyType
from typing import TYPE_CHECKING, Any, Literal

if TYPE_CHECKING:
    from collections.abc import Mapping

    from sensai.core.models.tools import ToolCall

type Role = Literal["system", "user", "assistant", "tool"]


@dataclass(frozen=True, slots=True)
class Message:
    """A message exchanged between a user, the model, and a tool."""

    role: Role
    content: str = ""
    tool_call_id: str | None = None
    tool_calls: tuple[ToolCall, ...] = ()
    tool_name: str | None = None
    reasoning_summary: str = ""

    def __post_init__(self) -> None:
        """Validate fields whose meaning depends on the message role."""
        if self.role not in (
            "system",
            "user",
            "assistant",
            "tool",
        ):
            raise ValueError(f"Invalid role {self.role!r}")
        if self.role == "tool" and not self.tool_name:
            raise ValueError("tool_name must be provided for role 'tool'")
        if self.role == "tool" and not self.tool_call_id:
            raise ValueError("tool_call_id must be provided for role 'tool'")
        if self.tool_calls and self.role != "assistant":
            raise ValueError("only assistant messages can carry tool_calls")
        if self.reasoning_summary and self.role != "assistant":
            raise ValueError("only assistant messages can have a reasoning_summary")
        if self.tool_name and self.role != "tool":
            raise ValueError("only tool messages can have a tool_name")

    @classmethod
    def system(cls, content: str) -> Message:
        """Build a system message."""
        return cls("system", content=content)

    @classmethod
    def user(cls, content: str) -> Message:
        """Build a user message."""
        return cls("user", content=content)

    @classmethod
    def assistant(
        cls,
        content: str = "",
        tool_calls: tuple[ToolCall, ...] = (),
        reasoning_summary: str = "",
    ) -> Message:
        """Build an assistant message, optionally containing tool calls."""
        return cls(
            "assistant",
            content=content,
            tool_calls=tool_calls,
            reasoning_summary=reasoning_summary,
        )

    @classmethod
    def tool(cls, content: str, tool_name: str, tool_call_id: str) -> Message:
        """Build a message containing a tool result."""
        return cls(
            "tool",
            content=content,
            tool_name=tool_name,
            tool_call_id=tool_call_id,
        )


@dataclass(frozen=True, slots=True, kw_only=True)
class ChatOptions:
    """Optional parameters controlling a model chat request."""

    temperature: float | None = None
    top_p: float | None = None
    seed: int | None = None
    num_ctx: int | None = None
    max_tokens: int | None = None
    response_schema: Mapping[str, Any] | None = field(default=None, hash=False)
    think: bool | None = None

    def __post_init__(self) -> None:
        """Freeze the response schema mapping."""
        if self.response_schema is not None:
            object.__setattr__(
                self, "response_schema", MappingProxyType(dict(self.response_schema))
            )


@dataclass(frozen=True, slots=True)
class Usage:
    """Token usage reported for a model response."""

    completion_tokens: int
    prompt_tokens: int

    def __post_init__(self) -> None:
        """Reject negative token counters."""
        if self.completion_tokens < 0:
            raise ValueError("completion_tokens must be non-negative")
        if self.prompt_tokens < 0:
            raise ValueError("prompt_tokens must be non-negative")

    @property
    def total_tokens(self) -> int:
        """Return the sum of prompt and completion tokens."""
        return self.prompt_tokens + self.completion_tokens


@dataclass(frozen=True, slots=True)
class ToolCallRequest:
    """Represent a tool call requested during model generation."""

    call: ToolCall


@dataclass(frozen=True, slots=True)
class TextDelta:
    """Represent a delta containing new text generated by the model."""

    text: str


@dataclass(frozen=True, slots=True)
class ThinkingDelta:
    """Represent a delta containing the model's internal reasoning or thoughts.

    `ready` is set on the last delta of a thought that concluded no more
    information is needed, so a front-end can tell that the answer comes next.
    """

    text: str
    ready: bool = False


@dataclass(frozen=True, slots=True)
class Timings:
    """Represent the time spent in various phases of a model response."""

    total: timedelta
    load: timedelta
    prompt_eval: timedelta
    eval: timedelta

    def __post_init__(self) -> None:
        """Reject negative durations."""
        for name in ("total", "load", "prompt_eval", "eval"):
            if getattr(self, name) < timedelta(0):
                raise ValueError(f"{name} must be non-negative")


@dataclass(frozen=True, slots=True)
class ChatDone:
    """Represent the completion of a chat session.

    `timings` is `None` when the model server does not report durations.
    """

    usage: Usage = field(default_factory=lambda: Usage(0, 0))
    done_reason: str | None = None
    timings: Timings | None = None

    @property
    def prompt_tokens_per_second(self) -> float | None:
        """Return the prompt processing speed, or `None` if it is unknown."""
        if self.timings is None:
            return None
        seconds = self.timings.prompt_eval.total_seconds()
        if seconds > 0:
            return self.usage.prompt_tokens / seconds
        else:
            return None

    @property
    def completion_tokens_per_second(self) -> float | None:
        """Return the generation speed, or `None` if it is unknown."""
        if self.timings is None:
            return None
        seconds = self.timings.eval.total_seconds()
        if seconds > 0:
            return self.usage.completion_tokens / seconds
        else:
            return None


type ChatEvent = TextDelta | ThinkingDelta | ToolCallRequest | ChatDone


@dataclass(frozen=True, slots=True, kw_only=True)
class LoadedModel:
    """A model currently loaded in memory by the model server.

    `context_length` is the context window the model was loaded with, or `None`
    when the server does not report it.
    """

    name: str
    size_bytes: int
    vram_bytes: int
    context_length: int | None = None

    def __post_init__(self) -> None:
        """Reject negative sizes and context lengths."""
        if self.size_bytes < 0:
            raise ValueError("size_bytes must be non-negative")
        if self.vram_bytes < 0:
            raise ValueError("vram_bytes must be non-negative")
        if self.context_length is not None and self.context_length < 0:
            raise ValueError("context_length must be non-negative")

    @property
    def ram_bytes(self) -> int:
        """Return the part of the model that spilled over to system memory."""
        return max(self.size_bytes - self.vram_bytes, 0)

    @property
    def fully_on_gpu(self) -> bool:
        """Tell whether the whole model fits in video memory."""
        return self.ram_bytes == 0


@dataclass(frozen=True, slots=True, kw_only=True)
class UsageTotals:
    """Token usage added up over several model responses, e.g. a whole session.

    `generation_time` adds up the time spent generating completion tokens, so
    it gives an average generation speed.
    """

    prompt_tokens: int = 0
    completion_tokens: int = 0
    calls: int = 0
    generation_time: timedelta = timedelta(0)

    def __post_init__(self) -> None:
        """Reject negative totals."""
        for name in ("prompt_tokens", "completion_tokens", "calls"):
            if getattr(self, name) < 0:
                raise ValueError(f"{name} must be non-negative")
        if self.generation_time < timedelta(0):
            raise ValueError("generation_time must be non-negative")

    def __add__(self, other: UsageTotals) -> UsageTotals:
        """Return the sum of two totals."""
        return UsageTotals(
            prompt_tokens=self.prompt_tokens + other.prompt_tokens,
            completion_tokens=self.completion_tokens + other.completion_tokens,
            calls=self.calls + other.calls,
            generation_time=self.generation_time + other.generation_time,
        )

    def add(self, done: ChatDone) -> UsageTotals:
        """Return these totals with one more model response counted."""
        return self + UsageTotals(
            prompt_tokens=done.usage.prompt_tokens,
            completion_tokens=done.usage.completion_tokens,
            calls=1,
            generation_time=done.timings.eval if done.timings else timedelta(0),
        )

    @property
    def total_tokens(self) -> int:
        """Return the sum of prompt and completion tokens."""
        return self.prompt_tokens + self.completion_tokens

    @property
    def completion_tokens_per_second(self) -> float | None:
        """Return the average generation speed, or `None` if it is unknown."""
        seconds = self.generation_time.total_seconds()
        if seconds > 0:
            return self.completion_tokens / seconds
        return None
